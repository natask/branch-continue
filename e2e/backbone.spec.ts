import { expect, test, type Download } from '@playwright/test'
import { readFile } from 'node:fs/promises'

test('Codex keeps edits made during a run and explains wording conflicts', async ({ page }, testInfo) => {
  test.skip(testInfo.project.name === 'tablet', 'Desktop and phone cover this workflow.')
  await page.addInitScript(() => {
    Object.defineProperty(window, 'showOpenFilePicker', { value: undefined })
  })
  await page.route('**/codex/account', (route) => route.fulfill({ json: { account: { type: 'chatgpt', email: 'test@example.com' }, requiresOpenaiAuth: false } }))
  let finishRun: (() => void) | undefined
  let runNumber = 0
  const submitted: any[] = []
  await page.route('**/agent-runs', async (route) => {
    submitted.push(route.request().postDataJSON())
    runNumber += 1
    await new Promise<void>((resolve) => { finishRun = resolve })
    await route.fulfill({ json: {
      runtimeId: 'local-codex', status: 'completed', response: 'Refined the page.',
      editedDocument: runNumber === 1 ? 'A precise outcome.' : 'A second suggestion.', externalId: 'test-codex-session',
    } })
  })
  await page.goto('/')
  const chooser = page.waitForEvent('filechooser')
  await page.getByRole('button', { name: 'Choose File', exact: true }).click()
  await (await chooser).setFiles({ name: 'concurrent.org', mimeType: 'text/plain', buffer: Buffer.from('* Existing page\nAn existing thought.\n') })
  await page.getByRole('button', { name: 'New Note', exact: true }).click()
  const editor = page.locator('.note-editor')
  const body = editor.locator('textarea.note-editor-body')
  await body.fill('A rough outcome.')
  await expect(editor.locator('.save-icon--saved')).toBeVisible()
  await editor.getByRole('button', { name: 'Enhance', exact: true }).click()
  const codex = page.getByRole('dialog', { name: 'Refine with Codex', exact: true })
  await codex.getByText('Instructions for this page', { exact: true }).click()
  const instructions = codex.getByLabel('Page system prompt', { exact: true })
  await instructions.fill('Keep my voice.')
  await expect(editor.locator('.save-icon--saved')).toBeVisible()
  await codex.getByRole('button', { name: 'Run on note', exact: true }).click()
  await expect(codex.getByRole('button', { name: 'Running…', exact: true })).toBeDisabled()
  await expect(codex.locator('.note-agent-run .codex-spinner')).toBeVisible()
  await expect(codex.locator('form')).toHaveAttribute('aria-busy', 'true')
  await expect.poll(() => Boolean(finishRun)).toBe(true)
  await instructions.fill('Keep examples and use short sentences.')
  await expect(editor.locator('.save-icon--saved')).toBeVisible()
  finishRun!()
  await expect(body).toHaveValue('A precise outcome.')
  await expect(instructions).toHaveValue('Keep examples and use short sentences.')
  await expect(codex.locator('.note-codex-session')).toContainText("Continue this note's Codex session")
  await expect(codex.locator('.note-agent-run .codex-spinner')).toHaveCount(0)

  finishRun = undefined
  await expect(editor.locator('.save-icon--saved')).toBeVisible()
  await codex.getByRole('button', { name: 'Run on note', exact: true }).click()
  await expect.poll(() => Boolean(finishRun)).toBe(true)
  expect(submitted[1].request.metadata.codexSessionId).toBe('test-codex-session')
  expect(submitted[1].request.context.threadId).toBe(submitted[0].request.context.threadId)
  expect(submitted[1].request.context.documentText).not.toContain('branch-continue-agent-task:start')
  expect(submitted[1].request.context.documentText).toContain('A precise outcome.')
  await codex.getByRole('button', { name: 'Done', exact: true }).click()
  await expect(editor.getByRole('button', { name: 'Enhance', exact: true })).toContainText('Running…')
  await expect(editor.locator('.note-enhance-button .codex-spinner')).toBeVisible()
  await body.fill('My own newer outcome.')
  await expect(editor.locator('.save-icon--saved')).toBeVisible()
  finishRun!()
  await editor.getByRole('button', { name: 'Enhance', exact: true }).click()
  const status = codex.locator('.note-agent-composer .agent-task-status')
  await expect(status).toContainText('Your edits were kept')
  await expect(status).not.toContainText('no answering runtime')
  await expect(body).toHaveValue('My own newer outcome.')
  await status.getByText('Task details', { exact: true }).click()
  await expect(status.locator('.agent-task-result')).toContainText('A second suggestion.')
})

test('Backbone saves portable note versions, ideas, and Codex page edits', async ({ page }, testInfo) => {
  test.skip(testInfo.project.name === 'tablet', 'Desktop and phone cover this workflow.')
  const downloads: Download[] = []
  page.on('download', (download) => downloads.push(download))
  await page.addInitScript(() => {
    Object.defineProperty(window, 'showOpenFilePicker', { value: undefined })
  })
  const liveCodex = process.env.BACKBONE_LIVE_CODEX === '1'
  if (liveCodex) test.setTimeout(150_000)
  if (!liveCodex) await page.route('**/codex/account', (route) => route.fulfill({ json: { account: { type: 'chatgpt', email: 'test@example.com' }, requiresOpenaiAuth: false } }))
  if (!liveCodex) await page.route('**/agent-runs', (route) => route.fulfill({ json: {
    runtimeId: 'local-codex', status: 'completed', response: 'Refined the page.', editedDocument: 'A precise outcome.', externalId: 'test-codex-session',
  } }))
  await page.goto('/')
  const chooser = page.waitForEvent('filechooser')
  await page.getByRole('button', { name: 'Choose File', exact: true }).click()
  await (await chooser).setFiles({ name: 'backbone-notes.org', mimeType: 'text/plain', buffer: Buffer.from('* Existing page\nAn existing thought.\n') })
  await expect(page.getByRole('heading', { name: 'Backbone', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'New Note', exact: true }).click()
  const editor = page.locator('.note-editor')
  const body = editor.locator('textarea.note-editor-body')
  await body.fill('A rough outcome.')
  await expect(editor.locator('.save-icon--saved')).toBeVisible()

  await editor.getByRole('button', { name: 'Ideas', exact: true }).click()
  const ideas = page.getByRole('dialog', { name: 'Ideas', exact: true })
  await ideas.getByRole('button', { name: '+ Idea', exact: true }).click()
  await ideas.getByLabel('Abstract point', { exact: true }).fill('The lasting meaning')
  await ideas.getByLabel('Meaning', { exact: true }).fill('Separate the point from its wording.')
  await ideas.getByLabel('Source passage', { exact: true }).fill('A rough outcome.')
  await ideas.getByRole('button', { name: 'Save idea', exact: true }).click()
  await expect(editor.locator('.save-icon--saved')).toBeVisible()
  await expect(body).toHaveValue('A rough outcome.')

  await ideas.getByRole('button', { name: 'Done', exact: true }).click()
  await editor.getByRole('button', { name: 'Versions', exact: true }).click()
  const history = page.getByRole('dialog', { name: 'Version history', exact: true })
  await history.getByRole('button', { name: 'Keep snapshot', exact: true }).click()
  const versions = history.getByRole('combobox', { name: 'Saved version', exact: true })
  await expect(versions.locator('option').filter({ hasText: 'snapshot' })).toHaveCount(1)
  const snapshotId = await versions.locator('option').filter({ hasText: 'snapshot' }).getAttribute('value')
  const initialCount = await versions.locator('option').count()
  await history.getByRole('button', { name: 'Done', exact: true }).click()
  await body.fill('A different outcome.')
  await expect(editor.locator('.save-icon--saved')).toBeVisible()
  await editor.getByRole('button', { name: 'Ideas', exact: true }).click()
  await expect(ideas.getByRole('button', { name: 'The lasting meaning', exact: true })).toBeVisible()
  await ideas.getByRole('button', { name: 'Done', exact: true }).click()
  await editor.getByRole('button', { name: 'Versions', exact: true }).click()
  await expect(versions.locator('option')).toHaveCount(initialCount + 1)
  await versions.selectOption(snapshotId!)
  await expect(history.locator('pre.note-version-preview')).toContainText('A rough outcome.')
  await expect(history.locator('pre.note-version-preview')).not.toContainText('backbone-concepts')
  await history.getByRole('button', { name: 'Previous version', exact: true }).click()
  await expect(versions).not.toHaveValue(snapshotId!)
  await history.getByRole('button', { name: 'Next version', exact: true }).click()
  await expect(versions).toHaveValue(snapshotId!)
  await history.getByRole('button', { name: 'Restore as new version', exact: true }).click()
  await expect(body).toHaveValue('A rough outcome.')
  await editor.getByRole('button', { name: 'Versions', exact: true }).click()
  await expect(versions.locator('option')).toHaveCount(initialCount + 2)
  await expect(versions.locator('option').filter({ hasText: 'restored' })).toHaveCount(1)

  await history.getByRole('button', { name: 'Done', exact: true }).click()

  const runCommand = async (label: string) => {
    await editor.getByRole('button', { name: /^(Commands|Search)$/ }).first().click()
    const dialog = page.getByRole('dialog', { name: 'Command palette' })
    await dialog.locator('.search-input').fill(label)
    await dialog.getByText(label, { exact: true }).click()
  }
  await runCommand('Undo Last Saved Change')
  await expect(body).toHaveValue('A different outcome.')
  await editor.getByRole('button', { name: 'Versions', exact: true }).click()
  await expect(versions.locator('option')).toHaveCount(initialCount + 3)
  await history.getByRole('button', { name: 'Done', exact: true }).click()
  await runCommand('Redo Last Saved Change')
  await expect(body).toHaveValue('A rough outcome.')
  await editor.getByRole('button', { name: 'Versions', exact: true }).click()
  await expect(versions.locator('option')).toHaveCount(initialCount + 4)

  await history.getByRole('button', { name: 'Done', exact: true }).click()
  await editor.getByRole('button', { name: /^(Commands|Search)$/ }).first().click()
  const palette = page.getByRole('dialog', { name: 'Command palette' })
  await expect(palette).toBeVisible()
  await palette.locator('.search-input').fill('Invoke Codex on This Page')
  await palette.getByText('Invoke Codex on This Page', { exact: true }).click()
  const codex = page.getByRole('dialog', { name: 'Refine with Codex', exact: true })
  await expect(codex.getByLabel('Ask Codex to edit this page')).toBeVisible()
  await codex.getByText('Instructions for this page', { exact: true }).click()
  await codex.getByLabel('Page system prompt', { exact: true }).fill('Keep the meaning and improve clarity.')
  await expect(editor.locator('.save-icon--saved')).toBeVisible()
  await codex.getByLabel('Ask Codex to edit this page').fill(liveCodex ? 'Replace the visible note wording with exactly: A precise outcome. Preserve all page metadata and ideas.' : 'Refine this page.')
  const firstResponse = page.waitForResponse((response) => response.url().endsWith('/agent-runs') && response.request().method() === 'POST', { timeout: liveCodex ? 120_000 : 5_000 })
  await codex.getByRole('button', { name: 'Run on note', exact: true }).click()
  const firstResult = await (await firstResponse).json()
  await expect(body).toHaveValue('A precise outcome.', { timeout: liveCodex ? 120_000 : 5_000 })
  await expect(codex.getByLabel('Page system prompt')).toHaveValue('Keep the meaning and improve clarity.')
  await expect(body).not.toHaveValue(/backbone-concepts|backbone-page-system/)
  if (liveCodex) {
    await expect(codex.getByRole('button', { name: 'Run on note', exact: true })).toBeEnabled()
    await expect(codex.locator('.note-codex-session')).toContainText("Continue this note's Codex session")
    await codex.getByLabel('Ask Codex to edit this page').fill('Keep the visible wording exactly: A precise outcome. Confirm briefly that this is a follow-up in the same conversation. Preserve the page metadata and ideas.')
    const followUpResponse = page.waitForResponse((response) => response.url().endsWith('/agent-runs') && response.request().method() === 'POST', { timeout: liveCodex ? 120_000 : 5_000 })
    await codex.getByRole('button', { name: 'Run on note', exact: true }).click()
    await expect(codex.locator('.note-agent-run .codex-spinner')).toBeVisible()
    const followUp = await followUpResponse
    const result = await followUp.json()
    expect(result.status).toBe('completed')
    expect(result.externalId).toBe(firstResult.externalId)
    expect(followUp.request().postDataJSON().request.metadata.codexSessionId).toBe(firstResult.externalId)
    await expect(codex.getByRole('button', { name: 'Run on note', exact: true })).toBeEnabled()
    await expect(body).toHaveValue('A precise outcome.')
  }
  await codex.getByRole('button', { name: 'Done', exact: true }).click()
  await editor.getByRole('button', { name: 'Ideas', exact: true }).click()
  await expect(ideas.getByRole('button', { name: 'The lasting meaning', exact: true })).toBeVisible()
  await ideas.getByRole('button', { name: 'Done', exact: true }).click()

  await expect.poll(() => downloads.length).toBeGreaterThan(4)
  const path = await downloads[downloads.length - 1].path()
  const saved = await readFile(path!, 'utf8')
  expect(saved).toContain('#+BACKBONE_EVENT: ')
  expect(saved).toContain('The lasting meaning')
  expect(saved).toContain('A precise outcome.')
  expect(saved).toContain('<!-- branch-continue-agent-task:start')
  expect(saved).toContain('Session: note-agent:')
  expect(saved.match(/^#\+BACKBONE_EVENT: /gm)!.length).toBeGreaterThan(initialCount)
  await page.screenshot({ path: `test-results/backbone-${testInfo.project.name}.png` })
})
